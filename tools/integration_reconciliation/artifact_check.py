"""Detect generated artifacts committed where they should not be.

Pattern-matches an already-gathered changed-files list (from
git_source.snapshot_branch) -- no filesystem or execution access needed,
so this is safe to run against a branch this checkout has never built.
"""
from __future__ import annotations

import fnmatch
from typing import Iterable

# Filename/path patterns that are near-certainly generated output rather
# than source, mirroring the kind of artifact this ecosystem's own
# pipelines (RunRecordV1 writers, manifest builders, benchmark reports)
# produce -- see docs/integration_reconciliation for the rationale on each.
GENERATED_ARTIFACT_PATTERNS: tuple[str, ...] = (
    "*.pyc",
    "__pycache__/*",
    "*RunRecord.json",
    "*/RunRecord.json",
    "*manifest.json",
    "*quality_report.json",
    "artifacts/*",
    "*/artifacts/*",
    "results/*",
    "*/results/*",
    "*.npz",
    "*.h5",
    "*.png",
    "*.pkl",
    "*.log",
)

# Patterns that look generated by the list above but are legitimate,
# intentionally-committed source/fixture/doc files -- excluded so the
# check does not cry wolf on this repository's own existing conventions
# (e.g. `docs/examples/*.json`, small committed test fixtures).
ALLOWED_EXCEPTIONS: tuple[str, ...] = (
    "docs/*",
    "*/docs/*",
    "tests/*/fixtures/*",
    "*/tests/*/fixtures/*",
    "governance/specs/*",
)


def find_suspect_artifacts(
    changed_files: Iterable[str],
    patterns: tuple[str, ...] = GENERATED_ARTIFACT_PATTERNS,
    allowed_exceptions: tuple[str, ...] = ALLOWED_EXCEPTIONS,
) -> list[str]:
    suspects: list[str] = []
    for path in changed_files:
        if any(fnmatch.fnmatch(path, exception) for exception in allowed_exceptions):
            continue
        if any(fnmatch.fnmatch(path, pattern) for pattern in patterns):
            suspects.append(path)
    return sorted(suspects)
